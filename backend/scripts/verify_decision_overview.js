// Decision page read isolation: no browser, network, DB, training or fixture writes.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const {App,ctx,elements} = require('./app_vm')();
vm.runInContext(fs.readFileSync(path.resolve(__dirname,'../../frontend/js/decision-overview.js'),'utf8'),ctx);
const page = vm.runInContext('DecisionOverviewPage',ctx);
const fixturePath = path.resolve(__dirname,'../data/train_js.json');
const originalFixture = crypto.createHash('sha256').update(fs.readFileSync(fixturePath)).digest('hex');
const fixture = JSON.parse(fs.readFileSync(fixturePath,'utf8'));
App.saveStore = () => { throw Error('Decision overview must never save live store'); };
App.switchCoarseEngine = App.retrainCoarseModelAsync = () => { throw Error('Decision overview must never change/train models'); };
const originalStore = JSON.parse(JSON.stringify(App.store));

let empty = page.buildSnapshot('gpt');
assert.equal(empty.model,null,'No GPT must not fall back to a DS model labelled GPT');
assert.equal(empty.showAdvice,false,'Empty data must not display current density as valid advice');
assert.equal(empty.coarse,null);
assert.equal(page.buildNodes(empty).find(n => n.id === 'raw-ash').value,'—');

App.store.coarseCoal = fixture.coarseCoal;
App.store.coarseModel = fixture.coarseModel;
App.store.coarseModelVariants = {ds:fixture.coarseModel};
App.store.coarseAshEma = {v:12.34,t:App._latestByTime(fixture.coarseCoal).timestamp};
App.store.floatCoal = [{timestamp:'2026-01-01',ash_content:8,coal_amount:5},{timestamp:'2026-02-01',ash_content:9,coal_amount:10}];
App.store.amountInputs = {denseAmount:{mode:'manual',manual:80},floatAmount:{mode:'auto',manual:null},coarseAmount:{mode:'manual',manual:10}};
let before = JSON.stringify(App.store);
let gptView = page.buildSnapshot('gpt');
assert.equal(gptView.productionEngine,'ds');
assert.equal(gptView.model,null);
assert.equal(gptView.ashes.coarse,12.34,'Read same timestamp must reuse stored EMA');
assert.equal(gptView.floating.timestamp,'2026-02-01','Latest uses record time, not array position');
assert.equal(page.buildNodes(gptView).find(n => n.id === 'float-amount').sampleAt,'2026-02-01','Automatic quantity uses record time, not stale manual time');
App.store.floatCoal.reverse();
assert.equal(page.buildSnapshot().floating.timestamp,'2026-02-01');
App.store.floatCoal.reverse();
for(let i=0;i<5;i++) page.buildSnapshot(i%2 ? 'gpt' : 'production');
assert.equal(JSON.stringify(App.store),before,'Views must not modify live state, EMA, autoState, models or revision');
assert.deepEqual(gptView.guide,page.buildSnapshot('production').guide,'Viewing GPT must not replace current production guidance');

// Synthetic GPT fixture used only to exercise UI range/imputation; no training claim.
const gpt = JSON.parse(JSON.stringify(fixture.coarseModel));
gpt.mlr.metrics.version = 2;
gpt.production = 'mlr';
gpt.mlr.inputPolicy = 'clip-training-range';
gpt.mlr.inputBounds = App.MLR_FEATURES.map(() => [0,100]);
gpt.mlr.imputeMeans = App.MLR_FEATURES.map(() => 20);
App.store.coarseModelVariants.gpt = gpt;
const record = JSON.parse(JSON.stringify(App._latestByTime(fixture.coarseCoal)));
record.raw_ash = 150; record.level = null; record.timestamp = '2026-10-01';
App.store.coarseCoal = [record];
before = JSON.stringify(App.store);
const preview = page.buildSnapshot('gpt');
assert.equal(preview.previewOnly,true);
assert.equal(preview.inputs.find(i => i.key === 'raw_ash').used,100);
assert.equal(preview.inputs.find(i => i.key === 'raw_ash').clipped,true);
assert.equal(preview.inputs.find(i => i.key === 'level').used,20);
assert.equal(preview.inputs.find(i => i.key === 'level').missing,true);
assert.ok(Number.isFinite(preview.prediction));
assert.equal(JSON.stringify(App.store),before,'New timestamp EMA is isolated too');

const floatRecord = App.store.floatCoal[1];
floatRecord.ash_content = null;
const incompleteFloat = page.buildSnapshot();
const defaultFloat = page.buildNodes(incompleteFloat).find(n => n.id === 'float-ash');
assert.match(defaultFloat.source,/默认/,'Existing row with missing ash must not be labelled measured');
assert.equal(defaultFloat.sampleAt,null);
floatRecord.ash_content = 9;

App.store.totalAshManualOn = true;
App.store.ashInputs.totalAsh = {manual:9.2,manualAt:Date.now(),sampleAt:null};
assert.equal(page.buildSnapshot().componentFeeds,false,'Manual total source makes components comparison inputs');
App.store.guideScheme = 'heavy';
assert.equal(page.buildSnapshot().componentFeeds,true,'Heavy scheme uses components to derive target');
App.store.guideScheme = 'total';
App.store.densityLastMoveAt = Date.now();
assert.equal(page.buildSnapshot().showAdvice,false,'Dwell holds must not look like target achieved');

ctx.window.Operations = {serverState:'online',telemetryFailed:false,telemetry:{items:[{source_id:'kep',key:'p',name:'<img onerror=bad>',available:true,status:'good',unit:'%',sample:{value:0,quality:'good'}}]}};
page.snapshot = page.buildSnapshot();
page.nodes = page.buildNodes(page.snapshot);
page.selected = 'raw-ash';
page.pointChoices['raw-ash'] = page.pointIdentity(ctx.window.Operations.telemetry.items[0]);
elements['decision-inspector'] = {};
page.renderInspector();
assert.match(elements['decision-inspector'].innerHTML, /&lt;img/);
assert.match(elements['decision-inspector'].innerHTML, />0 %/,'A valid zero is displayed');
assert.match(elements['decision-inspector'].innerHTML, /尚未参与本页计算/);
assert.equal(page.pointDisplay(page.nodes.find(n => n.id === 'raw-ash')).value, '—');
assert.equal(page.pointDisplay(page.nodes.find(n => n.id === 'raw-ash')).stopped, true);
const boundPoint = ctx.window.Operations.telemetry.items[0];
boundPoint.unit = '';
assert.equal(page.pointDisplay(page.nodes.find(n => n.id === 'raw-ash')).value, '—', 'No earlier nonzero must not invent a value');
assert.match(page.pointDisplay(page.nodes.find(n => n.id === 'raw-ash')).title, /单位未配置/);
boundPoint.sample.value = false;
assert.equal(page.pointDisplay(page.nodes.find(n => n.id === 'raw-ash')).value, '0', 'Boolean false is a valid reading');
boundPoint.sample.value = 0; boundPoint.unit = '%';
ctx.window.Operations.telemetryFailed = true;
assert.equal(page.pointDisplay(page.nodes.find(n => n.id === 'raw-ash')).value, '—', 'Failed query cannot leave an active card value');
page.renderInspector();
assert.match(elements['decision-inspector'].innerHTML, /查询中断/);
assert.match(elements['decision-inspector'].innerHTML, /0 %（不可用）/);
ctx.window.Operations.telemetry.items = [];
assert.equal(page.pointDisplay(page.nodes.find(n => n.id === 'raw-ash')).bound,true,'Missing point preserves display mapping');
assert.equal(page.pointDisplay(page.nodes.find(n => n.id === 'raw-ash')).value,'—');
page.renderInspector();
assert.match(elements['decision-inspector'].innerHTML,/采集查询中断/,'First failed query with no cached points must not look unconfigured');
assert.equal(page.telemetryState({status:'stale',sample:{quality:'good'}},false),'good · 接收超时','Good quality alone does not imply availability');
App.store.coarseAshInput = {manual:11,manualAt:Date.now()+60000};
App.store.autoState.coarseAsh = {v:12.34,t:0};
const manualCoarse = page.buildSnapshot('production');
assert.equal(page.buildNodes(manualCoarse).find(n => n.id === 'raw-ash').reference,true,'Manual coarse ash bypasses model inputs');
page.snapshot.ashes.coarse = null;
page.selected = 'coarse';
page.renderInspector();
assert.match(elements['decision-inspector'].innerHTML, /加权灰分贡献<\/dt><dd>—/,'Missing ash must not become a zero contribution');
App.store.coarseModelVariants.gpt = null;
App.store.coarseCoal[0].raw_ash = null;
const untrainedInput = page.buildNodes(page.buildSnapshot('gpt')).find(n => n.id === 'raw-ash');
assert.match(untrainedInput.description,/尚未训练/);
assert.doesNotMatch(untrainedInput.description,/按训练均值补齐/);

// Float summary follows the two displayed measures, not the parent's old point or other process factors.
const floating = page.nodes.find(n => n.id === 'float');
const floatAmount = page.nodes.find(n => n.id === 'float-amount');
floatAmount.value = '40.0 t/h';
const floatPoint = {source_id:'kep',key:'floatAsh',name:'浮精灰分',unit:'%',available:true,status:'good',sample:{value:9.3,quality:'good'}};
ctx.window.Operations.telemetry={items:[floatPoint]};
ctx.window.Operations.telemetryFailed=false;
page.pointChoices.float='["kep","obsolete-parent"]';
page.pointChoices['float-ash']=page.pointIdentity(floatPoint);
page.pointChoices['float-press']='["kep","unavailable-press"]';
const floatStoreBefore=JSON.stringify(App.store);
assert.equal(page.pointDisplay(floating).value,'9.3 %');
assert.equal(page.pointDisplay(floating).source,'煤量 40.0 t/h');
assert.equal(page.pointDisplay(floating).available,true,'An unavailable press is only a process reference');
page.selected='float';
page.renderInspector();
assert.match(elements['decision-inspector'].innerHTML,/显示值<\/dt><dd>9.3 %/);
assert.doesNotMatch(elements['decision-inspector'].innerHTML,/<select|当前业务值|加权灰分贡献/);
elements['decision-board']={};
elements['decision-toolbar-total']={};
page.renderGraph();
const floatEdge = from => elements['decision-board'].innerHTML.match(new RegExp(`<path class="decision-edge[^>]*data-decision-from="${from}"[^>]*>`))[0];
assert.doesNotMatch(floatEdge('float-ash'),/is-reference/);
assert.doesNotMatch(floatEdge('float-amount'),/is-reference/);
for(const id of ['float-press','float-unmodeled','float']) assert.match(floatEdge(id),/is-reference/);
floatPoint.sample.value=0;
assert.equal(page.pointDisplay(floating).value,'0 %','Float zero is not a device stoppage');
floatPoint.available=false;
assert.equal(page.pointDisplay(floating).value,'—');
assert.equal(page.pointDisplay(floating).source,'煤量 40.0 t/h');
assert.equal(page.pointDisplay(floating).badge,'部分缺失');
delete page.pointChoices['float-ash'];
assert.equal(page.pointDisplay(floating).value,page.pointDisplay(page.nodes.find(n => n.id === 'float-ash')).value,'Clearing the child selection restores the same business value in both cards');
assert.equal(JSON.stringify(App.store),floatStoreBefore,'Float summary cannot modify model or business state');
assert.equal(page.time(null),'未记录');
assert.match(page.time(Date.now()+86400000),/未来时间/);
assert.equal(crypto.createHash('sha256').update(fs.readFileSync(fixturePath)).digest('hex'),originalFixture);
App.store = originalStore;
console.log('Decision overview: read isolation, DS/GPT separation, EMA, input bounds, missing/hold states and telemetry checks passed.');
