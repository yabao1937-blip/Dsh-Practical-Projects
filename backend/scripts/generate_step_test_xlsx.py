"""生成 docs/密度阶跃实验-设计与验收.xlsx（P3：标定真实过程增益 g 的受控实验）。

为什么 0.01 步长不可行（本文的功效计算是自己算的，可复核）：
  模型 ΔA_i = g·Δρ_i + ε，ε~N(0,σ²) ⇒ SE(ĝ) = σ / (Δρ·√n)
  要求相对精度 SE/g ≤ 20% ⇒ n ≥ (σ / (0.2·g·Δρ))²
  取 g=15%/单位（专家表隐含区间 10~15）、σ=0.25%（单点化验+过程波动的合成）：
    Δρ=0.01 → n≈69 个事件；Δρ=0.02 → n≈17；Δρ=0.03 → n≈8
  ⇒ 步长翻倍，所需样本数按平方下降；这就是本方案坚持 0.02~0.03 的原因。
"""
