// No network or storage writes: alert lifecycle and merged UI state.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {App,ctx,elements} = require('./app_vm')();
vm.runInContext(fs.readFileSync(path.resolve(__dirname,'../../frontend/js/operations.js'),'utf8'),ctx);
const ops = ctx.window.Operations;
const handler = {};
for (const id of ['alert-count','status-alert-count','overview-alerts','active-alert-list']) elements[id]={};
elements['alert-badge']={dataset:{},setAttribute(k,v){this[k]=v;},addEventListener(k,v){handler[k]=v;}};
App.store.alerts = [{level:'严重',message:'已有灰分告警',time:'test'}];
const before=JSON.stringify(App.store);
const check = (status) => ({id:'kep:A303',device:'A303',status,received_at:'2026-10-08T03:00:00Z',
    message:status==='abnormal'?'A303 密度异常：实际 1.000，设定 1.480，偏差 0.480 > 阈值 0.300':'A303 数据不可用'});
ops.telemetry={density_alarm_checks:[check('abnormal')]};
App.renderAlerts();
assert.equal(elements['alert-count'].textContent,2);
assert.match(elements['alert-badge'].title,/A303/);
assert.match(elements['overview-alerts'].innerHTML,/A303.*0.480/);
ops.telemetryFailed=true;
App.renderAlerts();
assert.equal(elements['alert-count'].textContent,2);
assert.match(elements['active-alert-list'].innerHTML,/尚未确认恢复/);
ops.telemetryFailed=false; ops.telemetry.density_alarm_checks=[check('unknown')];
App.renderAlerts();
assert.match(elements['active-alert-list'].innerHTML,/实际 1.000.*尚未确认恢复/);
ops.telemetry.density_alarm_checks=[check('normal')];
App.renderAlerts();
assert.equal(elements['alert-count'].textContent,1,'Recovery keeps the existing ash alert');
assert.doesNotMatch(elements['overview-alerts'].innerHTML,/A303/);
ops.telemetry.density_alarm_checks=[{...check('abnormal'),message:'<img src=x onerror=evil()>'}];
App.renderAlerts();
assert.doesNotMatch(elements['overview-alerts'].innerHTML,/<img/);
assert.match(elements['overview-alerts'].innerHTML,/&lt;img/);
let opened=0;
App.openModal=(title,body)=>{assert.equal(title,'当前告警');assert.match(body,/active-alert-list/);opened++;};
handler.click(); handler.keydown({key:'Enter',preventDefault(){}}); handler.keydown({key:' ',preventDefault(){}});
assert.equal(opened,3);
assert.equal(JSON.stringify(App.store),before,'Telemetry alerts never modify business/model state');
console.log('Density alerts: raw deviation, unknown/recovery lifecycle, merged badge, modal, keyboard and escaping passed.');
