// Pure display checks: no network, training, SQLite or persisted state writes.
const assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path'), vm=require('node:vm');
const {App,ctx}=require('./app_vm')();
for(const file of ['decision-overview.js','decision-realtime.js','decision-sources.js','decision-hourly.js'])
    vm.runInContext(fs.readFileSync(path.resolve(__dirname,'../../frontend/js/'+file),'utf8'),ctx);
const page=vm.runInContext('DecisionOverviewPage',ctx), live=vm.runInContext('DecisionRealtime',ctx);
const before=JSON.stringify(App.store);
page.sharedSources=()=>true;
ctx.window.Operations={telemetryFailed:false};
const node={id:'raw-ash',unit:'%'}, item={source_id:'kep',key:'ash',available:true};
const cell={value:40,raw_value:40,status:'good',source_id:'kep',point_key:'ash',unit:'%'};
live.result={cells:{raw_ash:cell}};
const display={bound:true,shared:true,available:true,numericValue:40,item,unit:'%'};
const state=(d=display,n=node)=>page.heartbeatState(n,d);
const first=state();
assert.equal(first.status,'running');
assert.ok(state({...display,numericValue:80}).amplitude>first.amplitude,'Amplitude responds to the current reading');
assert.equal(JSON.stringify(state()),JSON.stringify(first),'Repeated rendering invents no sample history');
assert.equal(state({...display,numericValue:NaN}).status,'unavailable');
assert.equal(state({...display,numericValue:0}).status,'zero');
assert.equal(state({...display,held:true}).status,'unavailable');
assert.equal(state({...display,pending:true}).status,'unavailable');
cell.raw_value=0;cell.status='held';
const stopped={...display,available:false,held:true,stopped:true};
assert.equal(state(stopped).status,'stopped','Retained nonzero number must not animate a stopped meter');
assert.match(page.heartbeatMarkup(node,stopped),/d="M 0 14 H 72"/);
cell.status='good';cell.raw_value=40;
for(const status of ['manual','default','historical','calculated']) {cell.status=status;assert.equal(state(),null);}
cell.status='good';
assert.equal(state({...display,manual:true}),null);
assert.equal(state({...display,item:{...item,kind:'numeric_average'}}),null);
assert.equal(state(display,{id:'heavy',type:'component'}),null);
assert.equal(state(display,{id:'density',type:'root'}),null);
assert.equal(state(display,{id:'heavy-amount'}),null);
assert.equal(state({...display,bound:false}),null);
ctx.window.Operations.telemetryFailed=true;
assert.equal(state().status,'unavailable');ctx.window.Operations.telemetryFailed=false;
assert.equal(state({...display,item:{...item,available:false}}).status,'unavailable');
live.previousResult=live.result;live.result=null;
assert.equal(state().status,'unavailable','Old result preview must never drive the heartbeat');
live.result=live.previousResult;
const group={id:'desliming'}, parts=[{value:false,available:true},{value:false,available:true}];
live.result.cells.desliming={status:'good',source_id:'kep',value:{473:false,474:false}};
const groupDisplay={...display,components:parts,numericValue:null};
assert.equal(state(groupDisplay,group).status,'stopped');
parts[0].value=true;
assert.equal(state(groupDisplay,group).status,'running');
const half=state(groupDisplay,group).amplitude;parts[1].value=true;
assert.ok(state(groupDisplay,group).amplitude>half,'Group amplitude reflects running proportion');
parts[1].available=false;parts[1].value=null;
assert.equal(state(groupDisplay,group).status,'unavailable','Unknown switch is not a confirmed stop');
live.result.cells.level={...cell,observed_at:new Date(Date.now()-90000).toISOString(),alignment:{version:'gpt-level-lag-v1'}};
assert.equal(state(display,{id:'tail-level'}).status,'running','Valid 90-second aligned input is not mistaken for an outage');
live.result.cells.density={...cell,value:1.477};
assert.equal(state({...display,calculated:true,numericValue:1.477},{id:'density-current'}).status,'running','Direct density remains telemetry despite fallback wrapper');
page.aggregationMode='hourly';assert.equal(state(),null);
page.aggregationMode='instant';page.view='production';assert.equal(state(),null);
assert.equal(JSON.stringify(App.store),before,'Visual effect must not mutate business data or models');
console.log('Decision heartbeat: value, stop, quality, source and isolation checks passed.');
